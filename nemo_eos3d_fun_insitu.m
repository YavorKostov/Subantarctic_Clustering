function zn = nemo_eos3d_fun_insitu(so, thetao, pdep)
run params_eos80

            %
            zh  = pdep .* r1_Z0  ;                                % depth
            zt  = thetao .* r1_T0;                                          % temperature
            zs  = ( abs( so + rdeltaS ) .* r1_S0 ).^0.5;                    % square root salinity
            %
            zn3 = EOS013.*zt   ...
                + EOS103.*zs+EOS003;
            %
            zn2 = (EOS022.*zt   ...
                + EOS112.*zs+EOS012).*zt   ...
                + (EOS202.*zs+EOS102).*zs+EOS002;
            %
            zn1 = (((EOS041.*zt   ...
                + EOS131.*zs+EOS031).*zt   ...
                + (EOS221.*zs+EOS121).*zs+EOS021).*zt   ...
                + ((EOS311.*zs+EOS211).*zs+EOS111).*zs+EOS011).*zt   ...
                + (((EOS401.*zs+EOS301).*zs+EOS201).*zs+EOS101).*zs+EOS001;
            %
            zn0 = (((((EOS060.*zt   ...
                + EOS150.*zs+EOS050).*zt   ...
                + (EOS240.*zs+EOS140).*zs+EOS040).*zt   ...
                + ((EOS330.*zs+EOS230).*zs+EOS130).*zs+EOS030).*zt   ...
                + (((EOS420.*zs+EOS320).*zs+EOS220).*zs+EOS120).*zs+EOS020).*zt   ...
                + ((((EOS510.*zs+EOS410).*zs+EOS310).*zs+EOS210).*zs+EOS110).*zs+EOS010).*zt   ...
                + (((((EOS600.*zs+EOS500).*zs+EOS400).*zs+EOS300).*zs+EOS200).*zs+EOS100).*zs+EOS000;
            zn  = ( ( zn3 .* zh + zn2 ) .* zh + zn1 ) .* zh + zn0;

pp   =   pdep .* r1_Z0  ;

% vertical reference profile of density
R00 = 4.6494977072e+01; R01 = -5.2099962525e+00; R02 = 2.2601900708e-01;
R03 = 6.4326772569e-02; R04 = 1.5616995503e-02; R05 = -1.7243708991e-03;
r0 = ( ( ( ( ( R05*pp + R04 ).*pp + R03 ).*pp + R02 ).*pp + R01 ).*pp + R00 ).*pp ;

zn = zn +r0;
